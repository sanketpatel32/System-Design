/**
 * Regenerate lib/client-topics-index.ts from topics/*.md.
 * The index powers client-side search (CommandSearchModal) and embeds a
 * 160-character takeaway preview per topic.
 * Run after editing topic content: node scripts/gen-client-topics-index.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const TOPICS_DIR = path.join(ROOT, "topics");
const OUT = path.join(ROOT, "lib", "client-topics-index.ts");
const TOPIC_RE = /^(\d{3})_(.+)\.md$/;
const PREVIEW_LEN = 160;

function parseTopic(filename) {
  const raw = fs.readFileSync(path.join(TOPICS_DIR, filename), "utf8").replace(/\r\n/g, "\n");
  const slug = filename.match(TOPIC_RE)[2];
  const title = (raw.match(/^# (.+)$/m)?.[1] ?? slug).trim();
  const category = (raw.match(/^>\s*\*\*Category:\*\*\s*(.+?)\s*$/m)?.[1] ?? "Uncategorised").trim();
  const takeawayMatch = raw.split(/^###\s+Key\s+takeaway\s*$/im)[1];
  let takeaway = null;
  if (takeawayMatch) {
    takeaway = takeawayMatch.trim().split("\n")[0].trim() || null;
  }
  return {
    id: parseInt(filename.match(TOPIC_RE)[1], 10),
    slug,
    title,
    category,
    takeaway: takeaway ? takeaway.slice(0, PREVIEW_LEN) : null,
  };
}

const entries = fs
  .readdirSync(TOPICS_DIR)
  .filter((f) => TOPIC_RE.test(f))
  .sort()
  .map(parseTopic)
  .sort((a, b) => a.id - b.id);

const header =
  "/* eslint-disable */\n" +
  "// AUTO-GENERATED by scripts/gen-client-topics-index.mjs — do not edit by hand.\n" +
  "export interface ClientTopic { id: number; slug: string; title: string; category: string; takeaway: string | null; }\n\n" +
  "export const CLIENT_TOPICS: ClientTopic[] = ";

const body = JSON.stringify(entries, null, 2).replace(/"([a-zA-Z]+)":/g, '"$1":');
fs.writeFileSync(OUT, header + body + ";\n", "utf8");
console.log(`wrote ${entries.length} topics to lib/client-topics-index.ts`);
